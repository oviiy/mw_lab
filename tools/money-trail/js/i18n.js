const hasDom = typeof window !== 'undefined' && typeof localStorage !== 'undefined';
let lang = 'zh';
if (hasDom) {
  const saved = localStorage.getItem('sm-lang');
  lang = saved === 'en' || saved === 'zh' ? saved : (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  if (hasDom) {
    localStorage.setItem('sm-lang', l);
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
  }
}

