// Generates src/generated/{scenes,landmarks}.js from the files present in src/scenes + src/content.
import { readdirSync, existsSync, writeFileSync, mkdirSync, renameSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const ids = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.js') && !f.startsWith('_')).map((f) => f.slice(0, -3)) : []);
export async function generate() {
  mkdirSync('src/generated', { recursive: true });
  const scenes = ids('src/scenes'), contents = new Set(ids('src/content'));
  const have = scenes.filter((s) => contents.has(s)).sort();
  writeFileSync('src/generated/scenes.js', `// AUTO-GENERATED by tools/gen.mjs — do not edit.\nexport const SCENES = {\n${have.map((s) => `  '${s}': () => Promise.all([import('../scenes/${s}.js'), import('../content/${s}.js')]),`).join('\n')}\n};\nexport const CONTENT = {\n${have.map((s) => `  '${s}': () => import('../content/${s}.js'),`).join('\n')}\n};\n`);
  const index = [];
  for (const id of have) {
    try {
      const mod = await import(pathToFileURL(resolve(`src/content/${id}.js`)).href + `?t=${Date.now()}`);
      for (const [lid, lm] of Object.entries(mod.default.landmarks || {})) index.push({ loc: id, id: lid, en: lm.name.en, zh: lm.name.zh });
    } catch (e) { console.warn(`content/${id}.js skipped in landmark index: ${e.message}`); }
  }
  writeFileSync('src/generated/landmarks.js', `// AUTO-GENERATED by tools/gen.mjs — do not edit.\nexport const LANDMARK_INDEX = ${JSON.stringify(index)};\n`);
  await generateAtlasIndex();
  return have;
}

/** Slim, eager index of every place / house / person (for map + search); full records lazy-load per group. */
export async function generateAtlasIndex() {
  const imp = async (f) => (await import(pathToFileURL(resolve(f)).href + `?t=${Date.now()}`)).default;
  const { LOCATIONS } = await import(pathToFileURL(resolve('src/data/locations.js')).href + `?t=${Date.now()}`);
  const placeGroups = ids('src/data/places'), houseGroups = ids('src/data/houses');
  const places = new Map(), houses = [], people = [], placeHouses = new Map();
  for (const l of LOCATIONS) places.set(l.id, { id: l.id, kind: l.kind, region: l.region, at: l.at, rank: l.rank, names: l.names, alt: l.alt || [], explorable: true, group: null });
  for (const g of placeGroups) {
    let mod; try { mod = await imp(`src/data/places/${g}.js`); } catch (e) { console.warn(`places/${g}.js skipped: ${e.message}`); continue; }
    for (const p of mod.places || []) {
      const prev = places.get(p.id);
      if (prev) { prev.group = g; if (p.houses) placeHouses.set(p.id, p.houses); continue; }
      places.set(p.id, { id: p.id, kind: p.kind, region: p.region, at: p.at, rank: p.rank ?? 2, names: p.names, alt: p.alt || [], group: g });
      if (p.houses) placeHouses.set(p.id, p.houses);
    }
  }
  for (const g of houseGroups) {
    let mod; try { mod = await imp(`src/data/houses/${g}.js`); } catch (e) { console.warn(`houses/${g}.js skipped: ${e.message}`); continue; }
    for (const h of mod.houses || []) {
      houses.push({ id: h.id, names: h.names, region: h.region, seat: h.seat, tier: h.tier, colors: h.colors, group: g, tree: !!(h.members && h.members.length) });
      if (h.seat) { const list = placeHouses.get(h.seat) || []; if (!list.includes(h.id)) list.unshift(h.id); placeHouses.set(h.seat, list); }
      for (const m of h.members || []) people.push({ id: m.id, name: m.name, house: h.id, spoiler: !!m.spoiler });
    }
  }
  for (const [pid, hs] of placeHouses) { const p = places.get(pid); if (p) p.houses = hs; }
  const q = (o) => JSON.stringify(o);
  const tmp = `src/generated/.atlas-index.${process.pid}.js`;
  writeFileSync(tmp, `// AUTO-GENERATED by tools/gen.mjs — do not edit.
export const PLACE_INDEX = ${q([...places.values()])};
export const HOUSE_INDEX = ${q(houses)};
export const PEOPLE_INDEX = ${q(people)};
export const PLACE_GROUPS = {
${placeGroups.map((g) => `  '${g}': () => import('../data/places/${g}.js'),`).join('\n')}
};
export const HOUSE_GROUPS = {
${houseGroups.map((g) => `  '${g}': () => import('../data/houses/${g}.js'),`).join('\n')}
};
`);
  renameSync(tmp, 'src/generated/atlas-index.js'); // atomic swap: concurrent generators never expose a half-written file
  return { places: places.size, houses: houses.length, people: people.length };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) console.log('generated', (await generate()).length, 'scenes');
