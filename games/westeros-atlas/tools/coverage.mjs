// Generates docs/COVERAGE.md from the data + content files. Run: node tools/coverage.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { LOCATIONS } from '../src/data/locations.js';
import { regionById } from '../src/data/regions.js';

const rows = []; const tot = { lm: 0, cut: 0, high: 0, med: 0, low: 0 };
for (const l of LOCATIONS) {
  const c = (await import(pathToFileURL(resolve(`src/content/${l.id}.js`)).href)).default;
  const scene = readFileSync(`src/scenes/${l.id}.js`, 'utf8');
  const cut = /cutaways/.test(scene) ? (scene.match(/\bid:\s*['"][\w-]+['"]\s*,\s*name\s*:/g) || []).length : 0;
  const lms = Object.values(c.landmarks), n = lms.length, conf = { high: 0, medium: 0, low: 0 };
  lms.forEach((x) => conf[x.source.confidence]++);
  const checked = [...new Set((c.sources || []).map((s) => s.checked))].join(', ');
  rows.push(`| ${l.names.en} · ${l.names.zh} | \`${l.id}\` | ${l.kind} | ${regionById[l.region].names.en} | ${l.depth} | ${n} | ${cut || '–'} | ${conf.high}/${conf.medium}/${conf.low} | ${checked} |`);
  tot.lm += n; tot.cut += cut; tot.high += conf.high; tot.med += conf.medium; tot.low += conf.low;
}
const md = `# Coverage matrix (generated by \`node tools/coverage.mjs\`)

${LOCATIONS.length} explorable locations · ${tot.lm} clickable landmarks · ${tot.cut} cutaway interiors · confidence high/medium/low = ${tot.high}/${tot.med}/${tot.low}.
Every row opens a working 3D scene (enforced by \`npm test\` and \`tools/e2e.mjs\`).

| Place | id | Kind | Region | Depth | Landmarks | Cutaways | Conf. H/M/L | Source check modes |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

**Depth:** *deep* = strongly described in the books → richest scene · *moderate* → reconstruction with marked interpretation · *sparse* → restrained, mostly interpretive.

## Considered but not modelled (and why)
Region-level entries (the Reach, the Vale, Dorne …) appear as map regions with labels/fly-to, not as scenes. Smaller or thinly described places were left out to avoid inventing canon:
Duskendale, Maidenpool, the Dreadfort, Deepwood Motte, Karhold, Last Hearth, Starfall, Skyreach, Tarth, the Sisters, Bear Island, Skagos (islands/castles with little architectural detail in the novels);
Old Ghis, Lhazar, Bayasabhad, Sar Mell, Mantarys, Valysar, Hesh (barely described cities); Naath, Sothoryos' ports, Leng, Yi Ti's other cities (limits of the books' geography — shown as blank or schematic on the map).
They are candidates for future batches; see \`docs/PROGRESS.md\`.
`;
writeFileSync('docs/COVERAGE.md', md); console.log('wrote docs/COVERAGE.md', tot);
